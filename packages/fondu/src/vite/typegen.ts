import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, relative, sep } from 'node:path'

import type { Plugin } from 'vite'

import { isRouteFile, routePattern } from '../paths.js'

const OUT = 'app/fondu.gen.d.ts'

function walk(dir: string, out: string[] = [], base = dir): string[] {
  if (!existsSync(dir)) return out
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const file = join(dir, entry.name)
    if (entry.isDirectory()) walk(file, out, base)
    else out.push(relative(base, file).split(sep).join('/'))
  }
  return out
}

/** The registry the types are read from: page name → module, URL pattern → route module. Only `typeof import`s. */
export function generateTypes(root: string): string {
  const pages = walk(join(root, 'app/pages'))
    .filter((f) => /\.[jt]sx$/.test(f))
    .sort()
  const routes = walk(join(root, 'app/routes')).filter(isRouteFile).sort()
  const line = (key: string, path: string) => `      ${JSON.stringify(key)}: typeof import(${JSON.stringify(path)})`
  return `// Generated by fondu (vite dev / vite build). Commit it; do not edit.
declare module 'fondu' {
  interface Register {
    pages: {
${pages.map((f) => line(f.replace(/\.[jt]sx$/, ''), `./pages/${f.replace(/\.[jt]sx$/, '')}`)).join('\n')}
    }
    routes: {
${routes.map((f) => line(routePattern(f), `./routes/${f.replace(/\.ts$/, '')}`)).join('\n')}
    }
  }
}
export {}
`
}

export function writeTypes(root: string) {
  const file = join(root, OUT)
  const content = generateTypes(root)
  if (!existsSync(file) || readFileSync(file, 'utf8') !== content) writeFileSync(file, content)
}

export function typegen(): Plugin {
  let root = process.cwd()
  return {
    name: 'fondu:typegen',
    configResolved(c) {
      root = c.root
    },
    buildStart() {
      writeTypes(root)
    },
    configureServer(server) {
      const onChange = (file: string) => {
        const rel = relative(root, file).split(sep).join('/')
        if (rel.startsWith('app/pages/') || rel.startsWith('app/routes/')) writeTypes(root)
      }
      server.watcher.on('add', onChange)
      server.watcher.on('unlink', onChange)
    },
  }
}
